#!/bin/bash
# Embeds Resources/open-ac.applescript into Sources/ACVoiceSystem/OpenACScript.generated.swift and runs
# osacompile as a syntax check. osacompile only compiles: it sends no Apple Event and starts no app.
# Chrome terms resolve from Chrome's static scripting.sdef, so the check needs Google Chrome installed;
# without Chrome the check is skipped with a warning (use --require-compile to fail instead).
#
#   scripts/gen-applescript.sh                    # check syntax, then write the Swift file
#   scripts/gen-applescript.sh --check            # check syntax, fail (exit 1) when the Swift file is stale
#   scripts/gen-applescript.sh --no-compile       # skip osacompile
#   scripts/gen-applescript.sh --require-compile  # fail when osacompile cannot run
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC="$ROOT/Resources/open-ac.applescript"
OUT="$ROOT/Sources/ACVoiceSystem/OpenACScript.generated.swift"
CHECK=0
COMPILE=1
REQUIRE=0
while [ $# -gt 0 ]; do
  case "$1" in
    --check) CHECK=1 ;;
    --no-compile) COMPILE=0 ;;
    --require-compile) REQUIRE=1 ;;
    -h|--help) sed -n '2,10p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

with_timeout() { perl -e 'alarm shift; exec @ARGV' "$@"; }

[ -f "$SRC" ] || { echo "missing $SRC" >&2; exit 2; }

# The Swift raw string literal #"""..."""# must not see its own terminator or an escape.
if grep -q '"""#' "$SRC" || grep -q '\\#' "$SRC"; then
  echo "error: $SRC contains '\"\"\"#' or '\\#', which breaks the Swift raw string literal" >&2
  exit 2
fi

chrome_installed() {
  [ -d "/Applications/Google Chrome.app" ] && return 0
  [ -d "$HOME/Applications/Google Chrome.app" ] && return 0
  [ -n "$(with_timeout 10 mdfind 'kMDItemCFBundleIdentifier == "com.google.Chrome"' 2>/dev/null | head -1)" ]
}

TMP=$(mktemp -d "${TMPDIR:-/tmp}/acvoice-osa.XXXXXX")
trap 'rm -rf "$TMP"' EXIT

if [ "$COMPILE" = 1 ]; then
  if chrome_installed; then
    if ! with_timeout 60 /usr/bin/osacompile -o "$TMP/open-ac.scpt" "$SRC"; then
      echo "error: osacompile rejected $SRC" >&2
      exit 1
    fi
    echo "osacompile: ok"
  elif [ "$REQUIRE" = 1 ]; then
    echo "error: Google Chrome is not installed, osacompile cannot resolve its terms" >&2
    exit 1
  else
    echo "warning: Google Chrome is not installed, skipped osacompile" >&2
  fi
fi

SHA=$(shasum -a 256 "$SRC" | awk '{print $1}')
{
  echo "// Generated by scripts/gen-applescript.sh from Resources/open-ac.applescript. Do not edit by hand."
  echo ""
  echo "/// The Chrome AppleScript that \`ChromeOpener\` compiles once at launch."
  echo "enum OpenACScript {"
  echo "    /// SHA-256 of Resources/open-ac.applescript when this file was generated."
  echo "    static let sha256 = \"$SHA\""
  echo ""
  echo "    static let source = #\"\"\""
  cat "$SRC"
  # The closing delimiter needs a line of its own.
  if [ -n "$(tail -c 1 "$SRC")" ]; then echo ""; fi
  echo "\"\"\"#"
  echo "}"
} > "$TMP/OpenACScript.generated.swift"

if [ "$CHECK" = 1 ]; then
  if [ -f "$OUT" ] && cmp -s "$TMP/OpenACScript.generated.swift" "$OUT"; then
    echo "generated Swift: up to date"
    exit 0
  fi
  echo "error: $OUT is stale, run scripts/gen-applescript.sh" >&2
  exit 1
fi

cp "$TMP/OpenACScript.generated.swift" "$OUT"
echo "wrote $OUT"
